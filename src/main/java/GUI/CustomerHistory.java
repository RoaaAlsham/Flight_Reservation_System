    private void btn_showBoardingPassActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_showBoardingPassActionPerformed
        // TODO add your handling code here:
        if (reservationTable.getSelectedRow() == -1) {
            JOptionPane.showMessageDialog(mainFrame, "please select a flight to continue");
            return;
        }
        int reservationId = Integer.parseInt(dtm.getValueAt(reservationTable.getSelectedRow(), 0).toString());
        Reservation reservation = reservationOperations.getReservationByID(reservationId);
        BoardingPass boardingPass = new BoardingPass(mainFrame, reservation);
        mainFrame.mainPanel.add(boardingPass, "boardingPass");
        mainFrame.showPanelMethod("boardingPass");

    }//GEN-LAST:event_btn_showBoardingPassActionPerformed

