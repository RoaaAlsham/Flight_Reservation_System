    public Vector<String> prepareReservationRow(Reservation reservation) {
        Vector<String> row = new Vector<>();
        String reservationID = String.valueOf(reservation.getReservationId());
        String origin = reservation.getFlight().getOriginAirport().getCity();
        String destination = reservation.getFlight().getDestinationAirport().getCity();
        DateTimeFormatter formatter = DateTimeFormatter.ofPattern("dd-MM-yyyy HH:mm");
        String formattedDate = reservation.getFlight().getDepartureTime().format(formatter);
        String reservedSeats = String.valueOf(reservation.getReservedSeats().size());
        String price = String.valueOf(reservation.getTicketPrice());
        row.add(reservationID);
        row.add(origin);
        row.add(destination);
        row.add(formattedDate);
        row.add(reservedSeats);
        row.add(price);
        return row;
    }

