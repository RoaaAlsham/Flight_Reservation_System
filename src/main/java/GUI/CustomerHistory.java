    private void cancelReservationActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cancelReservationActionPerformed
        // TODO add your handling code here:
        if (reservationTable.getSelectedRow() == -1) {
            JOptionPane.showMessageDialog(mainFrame, "please select a flight to continue");
            return;
        }
        int reservationId = Integer.parseInt(dtm.getValueAt(reservationTable.getSelectedRow(), 0).toString());
        Reservation reservation = reservationOperations.getReservationByID(reservationId);
        if (reservation == null) {
            JOptionPane.showMessageDialog(mainFrame, "reservation not found");
            return;
        }
        LoggedinCustomer.getCustomerReservations().remove(reservation);
        reservationOperations.deleteReservationFromList(reservation);
        Flight flight = reservation.getFlight();
        flight.getReservations().remove(reservation);
        flight.unReserveSeats(reservation.getReservedSeats());

        JOptionPane.showMessageDialog(mainFrame, "Reservation canceled successfully.");

        // Refresh table
        dtm.setRowCount(0);
        setTableValues();
    }//GEN-LAST:event_cancelReservationActionPerformed


